-- ЛР9: схема цифрового профиля студента.
-- Скрипт пересоздаёт только таблицы учебного проекта.
DROP TABLE IF EXISTS activities;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   varchar(160) NOT NULL,
    login       varchar(80) NOT NULL UNIQUE,
    role        text NOT NULL CHECK (role IN ('Student', 'Reviewer', 'Manager'))
);

CREATE TABLE categories (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL UNIQUE
);

CREATE TABLE activities (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number               integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    title                varchar(80) NOT NULL CHECK (char_length(title) BETWEEN 5 AND 80),
    description          varchar(500) NOT NULL CHECK (char_length(description) BETWEEN 10 AND 500),
    category_id          integer NOT NULL REFERENCES categories (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status               text NOT NULL CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at           timestamptz NOT NULL DEFAULT now(),
    created_by_user_id   integer NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assignee_user_id     integer NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- Ускоряет выборки списка по статусу.
CREATE INDEX activities_status_idx ON activities (status);
-- Ускоряет фильтрацию и соединение записей с категориями.
CREATE INDEX activities_category_id_idx ON activities (category_id);

COMMENT ON TABLE activities IS 'Учебные, научные и проектные активности студента';
COMMENT ON COLUMN activities.number IS 'Человекочитаемый номер, отдельный от первичного ключа id';
COMMENT ON COLUMN activities.assignee_user_id IS 'Назначенный проверяющий; NULL до назначения';
